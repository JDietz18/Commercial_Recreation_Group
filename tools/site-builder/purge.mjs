// Build site/css/intera.css: Intera's third-party + template CSS, concatenated in
// cascade order and stripped of every rule the site's HTML and JS never use.
// Usage: node purge.mjs <site dir>
import { PurgeCSS } from 'purgecss';
import fs from 'node:fs';
import path from 'node:path';

const site = path.resolve(process.argv[2]);
// Intera's stylesheets, in cascade order. They live here, not in site/, because
// only the trimmed result is served. url()s in them are relative to site/css/.
const SOURCES = ['bootstrap.min.css', 'magnific-popup.css', 'style.css', 'templete.css', 'skin-crg-base.css']
  .map(f => path.join(path.dirname(new URL(import.meta.url).pathname), 'template-css', f));
const htmlFiles = [];
(function walk(d) {
  for (const f of fs.readdirSync(d, { withFileTypes: true })) {
    const p = path.join(d, f.name);
    if (f.isDirectory() && !['plugins', 'images', 'css', 'script'].includes(f.name)) walk(p);
    else if (f.name.endsWith('.html')) htmlFiles.push(p);
  }
})(site);
const content = [
  ...htmlFiles,
  // Not combining.js: it bundles many plugins the site doesn't use, and their
  // class-name strings would keep dead rules. Its runtime classes are safelisted.
  ...['theme.js', 'crg-site.js', 'crg-motion.js', 'crg-blueprint.js', 'quote-form.js']
    .map(f => path.join(site, 'js', f)),
];

let out = '';
for (const src of SOURCES) {
  const [res] = await new PurgeCSS().purge({
    content,
    css: [src],
    // Classes that scripts add at runtime (Bootstrap collapse, Magnific Popup,
    // sticky header, masonry filter) and states set by the browser.
    safelist: {
      standard: ['show', 'collapse', 'collapsing', 'collapsed', 'active', 'open', 'is-fixed', 'in', 'fade', 'disabled',
        'mobile-device', 'focused', 'filled', 'selected', 'animated', 'center', 'left', 'hidden', 'cloned'],
      greedy: [/^mfp-/],
    },
    variables: false,
    keyframes: true,
    fontFace: true,
  });
  out += `/* ---- ${path.basename(src)} ---- */\n` + res.css + '\n';
}
// No minifier: they round numbers (33.333333% -> 33.3333%) and rewrite shorthands,
// which shifts layout by fractions of a pixel. Only blank lines and comments go.
const code = out.replace(/\/\*(?!\s*----)[\s\S]*?\*\//g, '').replace(/\n\s*\n+/g, '\n');
const header = '/* Intera template CSS (Bootstrap 4, Magnific Popup, style.css, templete.css,\n' +
  '   skin-crg-base.css), with the rules this site never uses removed.\n' +
  '   Generated by tools/site-builder/purge.mjs from tools/site-builder/template-css/.\n' +
  '   Do not edit: change the sources, or override in crg-site.css. */\n';
fs.writeFileSync(path.join(site, 'css/intera.css'), header + code);
const before = SOURCES.reduce((n, s) => n + fs.statSync(s).size, 0);
console.log(`intera.css: ${before} -> ${header.length + code.length} bytes from ${htmlFiles.length} pages`);
